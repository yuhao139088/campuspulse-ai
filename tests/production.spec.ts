import { test, expect } from "@playwright/test";
import { readFileSync } from "node:fs";
import { join } from "node:path";

const credentials = readFileSync(join(process.cwd(), ".deployment-private/initial-account.txt"), "utf8").trim().split(/\r?\n/);
const fixture = process.env.PRODUCTION_CREDENTIALS_FILE ? JSON.parse(readFileSync(process.env.PRODUCTION_CREDENTIALS_FILE, "utf8")) : undefined;
const email = fixture?.email ?? credentials[0].split(": ")[1];
const password = fixture?.password ?? credentials[1].split(": ")[1];
test("production pages render real data, cloud state, bilingual controls and admin", async ({ page }, testInfo) => {
  const failures: string[] = [];
  page.on("pageerror", (problem) => failures.push(problem.message));
  page.on("console", (message) => { if (message.type() === "error" && /same key|NaN|hydration|TypeError/.test(message.text())) failures.push(message.text()); });
  await page.goto("/login");
  await page.locator('input[autocomplete="username"]').fill(email);
  await page.locator('input[type="password"]').fill(password);
  await page.getByRole("button", { name: "登录", exact: true }).click();
  await expect(page).toHaveURL(/\/dashboard$/, { timeout: 45000 });
  const spacesResponse = await page.request.get("/api/spaces");
  const spaces = await spacesResponse.json();
  const team = spaces.spaces.find((item: { slug: string }) => item.slug === "campuspulse-team");
  await Promise.all([page.waitForNavigation({ waitUntil: "domcontentloaded" }), page.locator(".workspace-controls select").selectOption(team.id)]);
  await expect(page.getByRole("heading", { name: fixture?.name ?? /郑宇豪/ })).toBeVisible();
  await page.getByRole("button", { name: "EN", exact: true }).click();
  await expect(page.getByRole("button", { name: "中", exact: true })).toBeVisible();
  await page.goto("/datasets");
  await expect(page.getByRole("heading", { name: "Your data assets" })).toBeVisible();
  await expect(page.getByText("上线验收数据.csv", { exact: true })).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath("datasets.png"), fullPage: true });
  await page.goto("/analysis");
  await expect(page.getByRole("heading", { name: "Ask the Agent about your data" })).toBeVisible();
  await expect(page.getByRole("button", { name: "Analyze", exact: true })).toBeDisabled();
  await page.goto("/canvas");
  await expect(page.getByRole("heading", { name: "Your data chart canvas" })).toBeVisible();
  await expect(page.getByRole("button", { name: "验收：签到人数", exact: true })).toBeVisible();
  await page.reload();
  await expect(page.getByRole("button", { name: "验收：签到人数", exact: true })).toBeVisible();
  await expect(page.getByText("6 source rows", { exact: true })).toBeVisible();
  await expect(page.locator(".board-chart canvas")).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath("canvas.png"), fullPage: true });
  await page.goto("/reports");
  await page.getByRole("button", { name: "上线验收数据分析报告", exact: true }).click();
  await expect(page.locator(".markdown-preview")).toContainText("Production verification.");
  await expect(page.getByRole("button", { name: "Download DOCX" })).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath("reports.png"), fullPage: true });
  await page.goto("/admin");
  await expect(page.getByRole("button", { name: "Members & invites" })).toBeVisible();
  await page.getByRole("button", { name: "Audit trail", exact: true }).click();
  await expect(page.getByText(/analysis.create/).first()).toBeVisible();
  await page.getByRole("button", { name: "Platform management", exact: true }).click();
  await expect(page.getByRole("heading", { name: "System configuration", exact: true })).toBeVisible();
  for (const section of ["Website identity", "Sign-in & registration", "Email delivery", "SMS delivery", "Human verification", "AI service", "Data imports", "Users & workspaces", "Platform audit"]) {
    await page.locator(".system-console-nav").getByRole("button", { name: section, exact: true }).click();
    await expect(page.locator(".system-console-content")).toBeVisible();
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 2)).toBe(true);
  }
  await page.locator(".system-console-nav").getByRole("button", { name: "Sign-in & registration", exact: true }).click();
  await page.screenshot({ path: testInfo.outputPath("admin.png"), fullPage: true });
  await page.goto("/settings");
  await expect(page.getByRole("heading", { name: "Service connections" })).toBeVisible();
  await expect(page.getByText("Configured", { exact: true })).toHaveCount(2);
  await expect(page.getByRole("heading", { name: "Account & sign-in security", exact: true })).toBeVisible();
  expect(failures).toEqual([]);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 2)).toBe(true);
});
